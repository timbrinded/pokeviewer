pub(crate) fn glyph(character: char) -> Option<&'static [u8; HEIGHT]> {
    let character = character.to_ascii_uppercase();
    let index = match character {
        'A'..='Z' => usize::from(character as u8 - b'A'),
        ' ' => 26,
        '-' => 27,
        '.' => 28,
        '\'' | '’' => 29,
        '/' => 30,
        '♀' => 31,
        '♂' => 32,
        _ => return None,
    };
    GLYPHS.get(index)
}

#[cfg(test)]
mod tests {
    use super::{GLYPHS, HEIGHT, glyph};

    #[test]
    fn complete_v1_character_set_has_fixed_storage() {
        assert_eq!(core::mem::size_of_val(&GLYPHS), 33 * HEIGHT);
        for character in "ABCDEFGHIJKLMNOPQRSTUVWXYZ -.'’/♀♂".chars() {
            assert!(glyph(character).is_some());
        }
        assert!(glyph('?').is_none());
    }
}
